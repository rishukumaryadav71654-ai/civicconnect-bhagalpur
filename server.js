app.post("/api/admin/login", (req, res) => {
  const pin = String(req.body.pin || "");

  if (pin !== ADMIN_PIN) {
    return res.status(401).json({
      error: "Wrong PIN"
    });
  }

  const token = crypto
    .randomBytes(32)
    .toString("hex");

  sessions.set(token, true);

  return res.json({
    token
  });
});

// =========================
// ADMIN LOGOUT
// =========================

app.post("/api/admin/logout", auth, (req, res) => {
  const token = (
    req.headers.authorization || ""
  ).replace("Bearer ", "");

  sessions.delete(token);

  return res.json({
    ok: true
  });
});

